const SUPPORTED = ['es', 'en'];

function detectInitial() {
  try {
    const stored = ySettings.get('lang');
    if (SUPPORTED.includes(stored)) return stored;
  } catch {}
  // Sin elección guardada: el idioma del sistema (español si es español; inglés en cualquier otro caso).
  try {
    const nav = String((typeof navigator !== 'undefined' && navigator.language) || '').toLowerCase();
    if (nav && !nav.startsWith('es')) return 'en';
  } catch {}
  return 'es';
}

let currentLang = detectInitial();
const listeners = new Set();

export function getLang() { return currentLang; }
export function supportedLangs() { return SUPPORTED.slice(); }

export function setLang(code) {
  if (!SUPPORTED.includes(code)) return;
  if (code === currentLang) return;
  currentLang = code;
  try { ySettings.set('lang', code); } catch {}
  for (const fn of listeners) {
    try { fn(code); } catch {}
  }
  try {
    if (typeof window !== 'undefined' && window.electronAPI && window.electronAPI.setLanguage) {
      window.electronAPI.setLanguage(code);
    }
  } catch {}
}

function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

export function t(key, vars) {
  const dict = DICT[currentLang] || DICT.es;
  const fallback = DICT.es;
  const raw = (dict[key] !== undefined ? dict[key] : (fallback[key] !== undefined ? fallback[key] : key));
  return interpolate(raw, vars);
}

export function useI18n() {
  const [, force] = useState(0);
  useEffect(() => {
    const fn = () => force(n => n + 1);
    listeners.add(fn);
    return () => { listeners.delete(fn); };
  }, []);
  return { t, lang: currentLang, setLang };
}

// React early to lang stored after first connect (Yjs may load async).
try {
  ySettings.observe(() => {
    const stored = ySettings.get('lang');
    if (SUPPORTED.includes(stored) && stored !== currentLang) {
      currentLang = stored;
      for (const fn of listeners) { try { fn(stored); } catch {} }
    }
  });
} catch {}

// Push initial value to main process so menu/tray pick it up at startup.
try {
  if (typeof window !== 'undefined') {
    const push = () => {
      if (window.electronAPI && window.electronAPI.setLanguage) {
        window.electronAPI.setLanguage(currentLang);
      }
    };
    if (document.readyState === 'complete') push();
    else window.addEventListener('load', push, { once: true });
  }
} catch {}
